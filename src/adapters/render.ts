import type { AgentSpec } from "../core/agent-spec.js";

/** Marker written into every file perezdev generates, so it never touches files it didn't create. */
export const GENERATOR = "perezdev";

/** Ownership marks from earlier releases, still recognized on read. */
const LEGACY_MARKS = ["x-perezdev: true", "x-inspo: true"];

type FrontmatterValue = string | boolean | string[] | Record<string, string>;

/**
 * Emit a string as a YAML scalar — plain when it's a simple word, otherwise a
 * JSON-encoded double-quoted scalar (valid YAML with correct escaping). Keeps a
 * tiny, dependency-free frontmatter writer instead of pulling in a YAML engine.
 */
function yamlScalar(s: string): string {
  if (/^[A-Za-z0-9][\w .,/()@+-]*$/.test(s) && !/^(true|false|null|yes|no|on|off)$/i.test(s)) return s;
  return JSON.stringify(s);
}

/** Serialize a small, known set of fields into a YAML frontmatter block (--- fenced). */
function buildFrontmatter(fields: Array<[string, FrontmatterValue]>): string {
  const lines = ["---"];
  for (const [k, v] of fields) {
    if (Array.isArray(v)) {
      lines.push(`${k}:`);
      for (const item of v) lines.push(`  - ${yamlScalar(item)}`);
    } else if (typeof v === "object") {
      lines.push(`${k}:`);
      for (const [mk, mv] of Object.entries(v)) lines.push(`  ${mk}: ${yamlScalar(mv)}`);
    } else if (typeof v === "boolean") {
      lines.push(`${k}: ${v}`);
    } else {
      lines.push(`${k}: ${yamlScalar(v)}`);
    }
  }
  lines.push("---");
  return lines.join("\n");
}

/**
 * "Use when…" phrasing — skill loaders decide relevance from the description
 * alone. Picks the connective that keeps the sentence grammatical:
 * "reviewing PRs" → "Use when reviewing PRs", "review PRs" → "Use to review PRs".
 */
export function triggerDescription(description: string): string {
  const desc = description.trim();
  const first = desc.split(/\s/, 1)[0]!.toLowerCase();
  const rest = `${desc.charAt(0).toLowerCase()}${desc.slice(1)}`;
  const trigger = /^use\b/i.test(desc)
    ? desc
    : first.endsWith("ing")
      ? `Use when ${rest}`
      : ["a", "an", "the"].includes(first)
        ? `Use for ${rest}`
        : `Use to ${rest}`;
  return trigger.replace(/\s*\.?$/, ".");
}

/** "pr-reviewer" → "Pr reviewer"; used as the document heading. */
function title(name: string): string {
  const words = name.replace(/-/g, " ");
  return words.charAt(0).toUpperCase() + words.slice(1);
}

/** Comment line identifying a generated markdown rule (placed after any frontmatter). */
function ruleStamp(spec: AgentSpec): string {
  return `<!-- generated by ${GENERATOR}: ${spec.name}@${spec.version} — change it with \`perezdev\`, not by hand -->`;
}

/** The description as written for loaders: generated ones get "Use when…" phrasing, added skills stay verbatim. */
function loaderDescription(spec: AgentSpec): string {
  return spec.origin ? spec.description.trim() : triggerDescription(spec.description);
}

/** The heading + body for rule files. Added skills already carry their own heading. */
function ruleBody(spec: AgentSpec): string[] {
  return spec.origin ? [spec.instructions.trim()] : [`# ${title(spec.name)}`, "", spec.instructions.trim()];
}

/**
 * An Agent Skills `SKILL.md` (agentskills.io). Skills added from a source are
 * reproduced byte-for-byte. Generated ones get `name` + `description` (the
 * fields every loader reads) with ownership and version in the standard
 * `metadata` map, so strict loaders don't trip on unknown keys.
 */
export function renderSkill(spec: AgentSpec): string {
  if (spec.origin && spec.frontmatter !== undefined) return `---\n${spec.frontmatter}\n---\n${spec.instructions}`;
  const fields: Array<[string, FrontmatterValue]> = [
    ["name", spec.name],
    ["description", loaderDescription(spec)],
  ];
  if (spec.allowedTools.length > 0) fields.push(["allowed-tools", spec.allowedTools]);
  fields.push(["metadata", { generator: GENERATOR, version: spec.version }]);
  const body = [`# ${title(spec.name)}`, "", spec.instructions.trim(), ""].join("\n");
  return `${buildFrontmatter(fields)}\n${body}`;
}

/** A plain markdown rule, for tools that load every rule file as always-on context (Cline, Roo). */
export function renderRule(spec: AgentSpec): string {
  const lines = [ruleStamp(spec)];
  if (!spec.origin) lines.push(`# ${title(spec.name)}`, "");
  lines.push(`**${loaderDescription(spec)}**`, "", spec.instructions.trim(), "");
  return lines.join("\n");
}

/** A Windsurf rule: `model_decision` loads the body only when the description matches the task. */
export function renderWindsurfRule(spec: AgentSpec): string {
  const frontmatter = buildFrontmatter([
    ["trigger", "model_decision"],
    ["description", loaderDescription(spec)],
  ]);
  return [frontmatter, ruleStamp(spec), ...ruleBody(spec), ""].join("\n");
}

/** Was this file content produced by perezdev (current or legacy marker)? */
export function isOwned(content: string): boolean {
  if (/^\s+generator:\s*perezdev\s*$/m.test(content)) return true;
  if (content.includes(`<!-- generated by ${GENERATOR}:`)) return true;
  return LEGACY_MARKS.some((m) => content.includes(m));
}
